#!/usr/bin/env bash
# Chimera phone-node installer for Ubuntu inside proot-distro (Termux).
#
# Run INSIDE proot Ubuntu, from the JARVIS repo:
#   bash scripts/proot_ubuntu_install.sh
#
# Or from native Termux (after `proot-distro install ubuntu`):
#   proot-distro login ubuntu -- bash /data/data/com.termux/files/home/Jarvis-2.0/scripts/proot_ubuntu_install.sh
#
# Why proot: Termux's default Python 3.14 has no Android pydantic-core wheel;
# Ubuntu proot uses normal linux_aarch64 wheels and avoids a Rust source build.
set -eu

TERMUX_HOME="${TERMUX_HOME:-/data/data/com.termux/files/home}"
TERMUX_BIN="/data/data/com.termux/files/usr/bin"
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"

echo "[1/5] Installing Ubuntu packages..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq python3 python3-pip python3-venv ca-certificates

echo "[2/5] Creating venv at $REPO_DIR/.venv-proot ..."
python3 -m venv "$REPO_DIR/.venv-proot"
# shellcheck disable=SC1091
source "$REPO_DIR/.venv-proot/bin/activate"
python -m pip install --upgrade pip wheel >/dev/null

echo "[3/5] Installing Python dependencies (pydantic + MQTT stack)..."
pip install aiomqtt paho-mqtt pydantic loguru python-dotenv pyyaml

echo "[4/5] Verifying imports..."
cd "$REPO_DIR"
python -c "from jarvis_node_sdk.transport import MqttTransport; print('ok: jarvis_node_sdk')"

ENV_FILE="$TERMUX_HOME/.chimera/node.env"
if [ ! -f "$ENV_FILE" ]; then
  echo "[5/5] Writing $ENV_FILE (interactive)..."
  mkdir -p "$TERMUX_HOME/.chimera"
  printf "Node id [nothing-phone-3a]: "
  read -r NODE_ID
  NODE_ID="${NODE_ID:-nothing-phone-3a}"
  printf "Spine HMAC key (Brain JARVIS_MQTT_HMAC_KEY): "
  read -r HMAC_KEY
  printf "Broker host (PC Tailscale IP): "
  read -r BROKER_HOST
  cat >"$ENV_FILE" <<EOF
CHIMERA_NODE_ID=$NODE_ID
CHIMERA_HMAC_KEY=$HMAC_KEY
CHIMERA_BROKER_HOST=$BROKER_HOST
CHIMERA_BROKER_PORT=1883
EOF
  chmod 600 "$ENV_FILE"
else
  echo "[5/5] Using existing $ENV_FILE"
fi

cat >"$REPO_DIR/scripts/run_chimera_proot_inner.sh" <<'INNER'
#!/usr/bin/env bash
# Generated by proot_ubuntu_install.sh — start the node inside proot Ubuntu.
set -eu
export PATH="/data/data/com.termux/files/usr/bin:${PATH:-}"
REPO="/data/data/com.termux/files/home/Jarvis-2.0"
ENV_FILE="/data/data/com.termux/files/home/.chimera/node.env"
cd "$REPO"
source "$REPO/.venv-proot/bin/activate"
exec python run_chimera_node.py --env-file "$ENV_FILE"
INNER
chmod +x "$REPO_DIR/scripts/run_chimera_proot_inner.sh"

echo
echo "Done. From native Termux, start the node with:"
echo "  bash $REPO_DIR/scripts/run_chimera_proot.sh"
echo
echo "Or inside proot Ubuntu:"
echo "  bash $REPO_DIR/scripts/run_chimera_proot_inner.sh"
echo
echo "Termux:API skills need Termux:API installed and PATH includes $TERMUX_BIN"
